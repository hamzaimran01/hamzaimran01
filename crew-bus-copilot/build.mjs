// Bundles the React + Blueprint app into dist/ so index.html opens by double-click (no server, no CDN).
import * as esbuild from 'esbuild';
import fs from 'node:fs';

// Register only the Blueprint icons the app uses (keeps the bundle small; no dynamic chunk loading on file://).
const used = new Set();
const scan = (dir) => fs.readdirSync(dir, { withFileTypes: true }).forEach((d) => {
  const p = dir + '/' + d.name;
  if (d.isDirectory()) return scan(p);
  if (!/\.(jsx?|mjs)$/.test(d.name) || d.name === 'icons.js') return;
  const src = fs.readFileSync(p, 'utf8');
  for (const m of src.matchAll(/\b(?:icon|leftIcon|endIcon|rightIcon)[=:]\s*\{?\s*["']([a-z0-9-]+)["']/g)) used.add(m[1]);
  for (const m of src.matchAll(/\[\s*'[^']*',\s*'[^']*',\s*'([a-z0-9-]+)'\s*\]/g)) used.add(m[1]);
  for (const m of src.matchAll(/(?:icon:|icon\s*=\s*)\s*'([a-z0-9-]+)'/g)) used.add(m[1]);
});
scan('src');
['help', 'info-sign', 'warning-sign', 'tick', 'cross', 'chevron-up', 'chevron-down', 'chevron-left', 'chevron-right', 'error', 'tick-circle', 'small-cross', 'search', 'caret-down', 'double-caret-vertical', 'play', 'pause', 'history', 'time', 'video', 'map', 'th-list', 'timeline-events', 'chart', 'drive-time', 'person', 'airplane', 'presentation', 'flash', 'notifications', 'shield', 'record', 'share', 'link', 'select', 'route', 'tag', 'people', 'exchange', 'swap-horizontal', 'undo', 'reset', 'manual', 'arrow-right', 'step-backward', 'step-forward', 'refresh', 'trash', 'endorsed', 'th'].forEach((n) => used.add(n));
const names = JSON.parse(fs.readFileSync('node_modules/@blueprintjs/icons/icons.json', 'utf8')).map((x) => x.iconName);
const valid = [...used].filter((n) => names.includes(n)).sort();
const bad = [...used].filter((n) => !names.includes(n));
if (bad.length) console.warn('Unknown icon names (ignored):', bad.join(', '));
const pascal = (n) => n.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const id = (n) => 'I' + pascal(n);
fs.writeFileSync('src/icons.js',
  '// Generated by build.mjs: only the Blueprint icons this app uses.\n' +
  "import { Icons } from '@blueprintjs/icons';\n" +
  valid.map((n) => "import " + id(n) + "16 from '@blueprintjs/icons/lib/esm/generated/16px/paths/" + n + ".js';\nimport " + id(n) + "20 from '@blueprintjs/icons/lib/esm/generated/20px/paths/" + n + ".js';").join('\n') + '\n' +
  'const P16 = {' + valid.map((n) => "'" + n + "': " + id(n) + '16').join(', ') + '};\n' +
  'const P20 = {' + valid.map((n) => "'" + n + "': " + id(n) + '20').join(', ') + '};\n' +
  'Icons.setLoaderOptions({ loader: async (name, size) => (size === 20 ? P20 : P16)[name] });\n' +
  'Icons.load(Object.keys(P16), 16);\nIcons.load(Object.keys(P20), 20);\n');

// The icon package's built-in loaders reference every icon; this app registers its own loader, so stub them out.
const stubIconLoaders = {
  name: 'stub-icon-loaders',
  setup(b) {
    b.onResolve({ filter: /(paths-loaders\/(allPathsLoader|splitPathsBySizeLoader)|\/allPaths)(\.js)?$/ }, (a) => ({ path: a.path, namespace: 'stub' }));
    b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({ contents: 'export const allPathsLoader = async () => undefined; export const splitPathsBySizeLoader = async () => undefined; export const IconSvgPaths16 = {}; export const IconSvgPaths20 = {}; export function getIconPaths() { return undefined; } export function iconNameToPathsRecordKey(n) { return n; }', loader: 'js' }));
  }
};
const opts = {
  plugins: [stubIconLoaders],
  entryPoints: ['src/main.jsx'], bundle: true, minify: true, format: 'iife', target: ['es2019'],
  outfile: 'dist/app.js', loader: { '.js': 'jsx', '.woff': 'file', '.woff2': 'file', '.ttf': 'file', '.eot': 'file', '.svg': 'dataurl' },
  define: { 'process.env.NODE_ENV': '"production"' }, legalComments: 'linked', logLevel: 'info', jsx: 'automatic'
};
if (process.argv.includes('--watch')) { const c = await esbuild.context(opts); await c.watch(); }
else { await esbuild.build(opts); console.log('Icons bundled:', valid.length); }
